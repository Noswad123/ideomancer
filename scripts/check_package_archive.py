"""Bounded, read-only current-candidate .crate integrity checks (Python 3.12+).

This is not authenticity or ownership approval, nor an OS sandbox. The trusted
reviewer's inventory is never read from the archive. Source comparison is opt-in;
Extracted comparison rejects extras except a real top-level target/ directory,
whose contents are not inspected. Unreviewed empty directories are rejected too.
Only ordinary tar files/directories are accepted, not tar extension records.
Manifest parity is deliberately limited to this candidate's crates.io-only
dependencies and conventional library, binary and test targets, not general
Cargo normalization. Filesystem guards require POSIX Linux/macOS semantics and
reject even OS symlink aliases above comparison roots (for example /var).
"""

import argparse
from contextlib import contextmanager, ExitStack
import gzip
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat
import sys
import tarfile
import tomllib
import zlib

from check_package import GENERATED_OPTIONAL, PolicyError, checked_path, inventory, verify


MAX_COMPRESSED = 32 * 1024 * 1024
MAX_TOTAL = 64 * 1024 * 1024
MAX_FILE = 8 * 1024 * 1024
MAX_MEMBERS = 512
MAX_TREE_ENTRIES = 1024
CHUNK = 64 * 1024
ROOT = "ideomancer-0.1.0"
NORMALIZED_HEADER = b"# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO\n"


def identity(info):
    return (info.st_dev, info.st_ino, info.st_mode, info.st_size,
            info.st_mtime_ns, info.st_ctime_ns)


@contextmanager
def checked_file(root, name):
    """Open without following symlinks, then check basic concurrent replacement.

    Directory-relative opens also reject symlinks above the supplied root. This
    is a race guard, not a guarantee against a malicious concurrent filesystem.
    """
    parts = Path(os.path.abspath(root)).parts[1:] + tuple(name.split("/"))
    with ExitStack() as stack:
        directory = os.open("/", os.O_RDONLY | os.O_DIRECTORY)
        stack.callback(os.close, directory)
        for part in parts[:-1]:
            directory = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                                dir_fd=directory)
            stack.callback(os.close, directory)
        fd = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK,
                     dir_fd=directory)
        stream = stack.enter_context(os.fdopen(fd, "rb"))
        before = os.fstat(stream.fileno())
        if not stat.S_ISREG(before.st_mode) or before.st_size > MAX_FILE:
            raise PolicyError("comparison requires a bounded regular file")
        yield stream
        after = os.fstat(stream.fileno())
        current = os.stat(parts[-1], dir_fd=directory, follow_symlinks=False)
        if identity(before) != identity(after) or identity(before) != identity(current):
            raise PolicyError("comparison file changed during verification")


def dependency_tables(manifest):
    """Canonicalize only this candidate's registry dependency syntax/defaults."""
    kinds = {"dependencies", "dev-dependencies", "build-dependencies"}
    targets = manifest.get("target", {})
    if not isinstance(targets, dict):
        raise ValueError
    result = {}
    for target, table in [(None, manifest), *targets.items()]:
        if not isinstance(table, dict) or (target is not None and set(table) - kinds):
            raise ValueError
        dependencies = {}
        for kind in sorted(kinds):
            entries = table.get(kind, {})
            if not isinstance(entries, dict):
                raise ValueError
            dependencies[kind] = {}
            for name, request in entries.items():
                if isinstance(request, str):
                    request = {"version": request}
                if not isinstance(request, dict) or set(request) - {
                    "version", "features", "default-features", "optional", "package"
                }:
                    # Alternate registry mapping and path/git/workspace rewriting
                    # are intentionally unsupported for this current candidate.
                    raise ValueError
                version = request.get("version")
                package = request.get("package", name)
                features = request.get("features", [])
                defaults = request.get("default-features", True)
                optional = request.get("optional", False)
                if (not isinstance(version, str) or not version
                        or not isinstance(package, str) or not package
                        or not isinstance(features, list)
                        or any(not isinstance(feature, str) for feature in features)
                        or type(defaults) is not bool or type(optional) is not bool):
                    raise ValueError
                dependencies[kind][name] = (version, package, sorted(set(features)), defaults, optional)
        result[target] = dependencies
    return result


def check_extracted_tree(root, files):
    """Bounded no-follow scan; target/ is unused by the external-target consumer.

    Directory metadata guards detect basic concurrent changes during the scan,
    not changes after verification or malicious concurrent filesystem activity.
    """
    directories = {str(parent) for name in files for parent in PurePosixPath(name).parents
                   if str(parent) != "."}
    count = 0

    def scan(directory, prefix):
        nonlocal count
        before = os.fstat(directory)
        with os.scandir(directory) as entries:
            for entry in entries:
                count += 1
                if count > MAX_TREE_ENTRIES:
                    raise PolicyError("extracted tree exceeds entry count limit")
                name = prefix + entry.name
                info = entry.stat(follow_symlinks=False)
                if stat.S_ISDIR(info.st_mode):
                    if name == "target":
                        continue
                    if name not in directories:
                        raise PolicyError("unreviewed extracted directory")
                    child = os.open(entry.name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                                    dir_fd=directory)
                    try:
                        if identity(info) != identity(os.fstat(child)):
                            raise PolicyError("extracted directory changed during verification")
                        scan(child, name + "/")
                        current = os.stat(entry.name, dir_fd=directory, follow_symlinks=False)
                        if identity(info) != identity(current):
                            raise PolicyError("extracted directory changed during verification")
                    finally:
                        os.close(child)
                elif not stat.S_ISREG(info.st_mode) or name not in files:
                    raise PolicyError("unreviewed or nonregular extracted file")
        if identity(before) != identity(os.fstat(directory)):
            raise PolicyError("extracted directory changed during verification")

    with ExitStack() as stack:
        directory = os.open("/", os.O_RDONLY | os.O_DIRECTORY)
        stack.callback(os.close, directory)
        for part in Path(os.path.abspath(root)).parts[1:]:
            directory = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                                dir_fd=directory)
            stack.callback(os.close, directory)
        scan(directory, "")


def manifest_features(manifest):
    features = manifest.get("features", {})
    if not isinstance(features, dict):
        raise ValueError
    result = {}
    for name, values in features.items():
        if not isinstance(values, list) or any(not isinstance(value, str) for value in values):
            raise ValueError
        result[name] = sorted(set(values))
    return result


def validate_manifests(normalized, original, paths):
    if not normalized.startswith(NORMALIZED_HEADER):
        raise PolicyError("expected Cargo-normalized manifest header")
    try:
        manifest = tomllib.loads(normalized.decode("utf-8"))
        source = tomllib.loads(original.decode("utf-8"))
        package = manifest["package"]
        old = source["package"]
        for key in ("build", "autolib", "autobins", "autoexamples", "autotests", "autobenches"):
            if package.get(key) is not False:
                raise ValueError
        for field, value in (("name", "ideomancer"), ("version", "0.1.0"),
                             ("rust-version", "1.89"), ("license", "MIT")):
            if package.get(field) != value or old.get(field) != value:
                raise ValueError
        allowed = {"package", "lib", "bin", "test", "dependencies", "dev-dependencies",
                   "build-dependencies", "target", "features"}
        if set(manifest) - allowed or set(source) - (allowed - {"bin", "test"}):
            raise ValueError
        # Cargo adds discovery switches, inferred readme, and build=false. All
        # other package fields must stay identical to the checked original.
        packages = []
        for table, automatic in ((old, True), (package, False)):
            table = dict(table)
            if table.pop("build", False) is not False or "links" in table:
                raise ValueError
            for key in ("autolib", "autobins", "autoexamples", "autotests", "autobenches"):
                if key in table and table.pop(key) is not automatic:
                    raise ValueError
            table.setdefault("readme", "README.md")
            packages.append(table)
        if packages[0] != packages[1]:
            raise ValueError
        library_defaults = {"name": "ideomancer_core", "path": "src/lib.rs",
                            "proc-macro": False, "test": True, "doctest": True,
                            "bench": True, "doc": True, "harness": True,
                            "edition": old.get("edition", "2015"), "crate-type": ["lib"]}
        for table in (source.get("lib", {}), manifest.get("lib", {})):
            if not isinstance(table, dict) or set(table) - library_defaults.keys():
                raise ValueError
            if table.get("name") != "ideomancer_core":
                raise ValueError
            for key, default in library_defaults.items():
                value = table.get(key, default)
                if type(value) is not type(default) or value != default:
                    raise ValueError
        if manifest.get("lib", {}).get("path") != "src/lib.rs":
            raise ValueError
        if manifest.get("bin") != [{"name": "ideomancer", "path": "src/main.rs"}]:
            raise ValueError
        if "src/main.rs" not in paths:
            raise ValueError
        tests = manifest.get("test", [])
        if not isinstance(tests, list):
            raise ValueError
        test_paths = set()
        for test in tests:
            if (not isinstance(test, dict) or set(test) != {"name", "path"}
                    or not isinstance(test["name"], str)
                    or not re.fullmatch(r"[A-Za-z0-9_-]+", test["name"])
                    or test["path"] != f"tests/{test['name']}.rs"
                    or test["path"] in test_paths):
                raise ValueError
            test_paths.add(test["path"])
        if test_paths != {path for path in paths if re.fullmatch(r"tests/[^/]+\.rs", path)}:
            raise ValueError
        if dependency_tables(manifest) != dependency_tables(source):
            raise ValueError
        if manifest_features(manifest) != manifest_features(source):
            raise ValueError
        return {key: package[key] for key in ("name", "version", "rust-version", "license")}
    except (ValueError, KeyError, TypeError, AttributeError, RecursionError):
        raise PolicyError("invalid packaged manifests") from None


def validate_vcs(data):
    def unique_object(pairs):
        result = dict(pairs)
        if len(result) != len(pairs):
            raise ValueError
        return result

    try:
        value = json.loads(data, object_pairs_hook=unique_object)
        git = value["git"]
        if (set(value) != {"git", "path_in_vcs"} or set(git) not in ({"sha1"}, {"sha1", "dirty"})
                or not isinstance(git["sha1"], str)
                or not re.fullmatch(r"[0-9a-fA-F]{40}", git["sha1"])
                or type(git.get("dirty", False)) is not bool or value["path_in_vcs"] != ""):
            raise ValueError
        return {"sha1": git["sha1"], "dirty": git.get("dirty", False)}
    except (ValueError, KeyError, TypeError, UnicodeError, RecursionError):
        raise PolicyError("invalid Cargo VCS receipt") from None


def verify_archive(archive: Path, expected: set, source_dir: Path | None = None,
                   extracted_dir: Path | None = None) -> dict:
    """Return a JSON-safe receipt; raise PolicyError/OSError on failed integrity.

    expected is the TRUSTED reviewer inventory, including Cargo.toml.orig and
    excluding optional .cargo_vcs_info.json. No Cargo commands or writes occur.
    """
    expected = inventory("\n".join(sorted(expected)))
    required = {"Cargo.toml", "Cargo.toml.orig", "src/lib.rs"}
    if not required <= expected:
        raise PolicyError("inventory lacks required package identity files")
    names, files, metadata = set(), set(), {}
    total = expanded = 0
    # Bound decompression including headers, padding, and trailing zero blocks.
    expanded_limit = MAX_TOTAL + MAX_MEMBERS * 1024 + 1024 * 1024
    try:
        with os.fdopen(os.open(archive, os.O_RDONLY | os.O_NONBLOCK), "rb") as raw:
            before = os.fstat(raw.fileno())
            if not stat.S_ISREG(before.st_mode) or before.st_size > MAX_COMPRESSED:
                raise PolicyError("archive exceeds compressed size limit or is not regular")
            digest = hashlib.sha256()
            hashed = 0
            while block := raw.read(CHUNK):
                hashed += len(block)
                if hashed > MAX_COMPRESSED:
                    raise PolicyError("archive exceeds compressed size limit")
                digest.update(block)
            raw.seek(0)
            with gzip.GzipFile(fileobj=raw, mode="rb") as zipped:
                def read_exact(size):
                    nonlocal expanded
                    chunks = []
                    while size:
                        block = zipped.read(min(size, CHUNK))
                        if not block:
                            raise PolicyError("truncated tar archive")
                        expanded += len(block)
                        if expanded > expanded_limit:
                            raise PolicyError("archive exceeds expanded size limit")
                        chunks.append(block)
                        size -= len(block)
                    return b"".join(chunks)

                while True:
                    header = read_exact(512)
                    if header == bytes(512):
                        if read_exact(512) != bytes(512):
                            raise PolicyError("invalid tar end marker")
                        # Drain through gzip's CRC/trailer checks, with a hard bound.
                        while block := zipped.read(CHUNK):
                            expanded += len(block)
                            if expanded > expanded_limit or any(block):
                                raise PolicyError("invalid or excessive trailing tar data")
                        break
                    member = tarfile.TarInfo.frombuf(header, "utf-8", "strict")
                    stored_name = header[:100].split(b"\0", 1)[0].decode("utf-8")
                    prefix = header[345:500].split(b"\0", 1)[0].decode("utf-8")
                    if prefix:
                        stored_name = prefix + "/" + stored_name
                    if stored_name not in ({member.name, member.name + "/"} if member.isdir() else {member.name}):
                        raise PolicyError("noncanonical archive member path")
                    if len(names) >= MAX_MEMBERS:
                        raise PolicyError("archive exceeds member count limit")
                    if member.type not in (tarfile.REGTYPE, tarfile.AREGTYPE, tarfile.DIRTYPE):
                        raise PolicyError("only regular files and canonical directories are allowed")
                    name = member.name
                    if member.isdir() and name.endswith("/"):
                        name = name[:-1]
                    if name in names:
                        raise PolicyError("duplicate archive member")
                    names.add(name)
                    if name == ROOT and member.isdir():
                        relative = None
                    elif name.startswith(ROOT + "/"):
                        relative = name[len(ROOT) + 1:]
                        if not member.isdir():
                            checked_path(relative)
                    else:
                        raise PolicyError("unexpected archive root")
                    if member.size < 0 or member.size > MAX_FILE:
                        raise PolicyError("archive member exceeds size limit")
                    if member.isdir():
                        if member.size or (relative is not None and not any(
                            item.startswith(relative + "/") for item in expected | GENERATED_OPTIONAL
                        )):
                            raise PolicyError("unreviewed archive directory")
                        continue
                    if relative not in expected | GENERATED_OPTIONAL:
                        raise PolicyError("unreviewed archive file")
                    files.add(relative)
                    total += member.size
                    if total > MAX_TOTAL:
                        raise PolicyError("archive exceeds total member size limit")
                    with ExitStack() as comparisons:
                        streams = []
                        if source_dir is not None and relative not in {"Cargo.toml", *GENERATED_OPTIONAL}:
                            source_name = "Cargo.toml" if relative == "Cargo.toml.orig" else relative
                            streams.append(comparisons.enter_context(checked_file(source_dir, source_name)))
                        if extracted_dir is not None:
                            streams.append(comparisons.enter_context(checked_file(extracted_dir, relative)))
                        remaining = member.size
                        capture = relative in {"Cargo.toml", "Cargo.toml.orig", ".cargo_vcs_info.json"}
                        content = bytearray()
                        while remaining:
                            block = read_exact(min(remaining, CHUNK))
                            remaining -= len(block)
                            for stream in streams:
                                if stream.read(len(block)) != block:
                                    raise PolicyError(f"comparison content mismatch: {relative}")
                            if capture:
                                content.extend(block)
                        for stream in streams:
                            if stream.read(1):
                                raise PolicyError(f"comparison length mismatch: {relative}")
                        if capture:
                            metadata[relative] = bytes(content)
                    if any(read_exact(-member.size % 512)):
                        raise PolicyError("nonzero tar member padding")
            if identity(before) != identity(os.fstat(raw.fileno())) or hashed != before.st_size:
                raise PolicyError("archive changed during verification")
        count = verify(expected, files)
        package = validate_manifests(metadata["Cargo.toml"], metadata["Cargo.toml.orig"], files)
        vcs = validate_vcs(metadata[".cargo_vcs_info.json"]) if ".cargo_vcs_info.json" in metadata else None
        if extracted_dir is not None:
            check_extracted_tree(extracted_dir, files)
        return {"schema_version": "ideomancer.package-archive.v1", "status": "passed",
                "archive_sha256": digest.hexdigest(), "package": package, "file_count": count,
                "vcs": vcs, "matched_source": source_dir is not None,
                "matched_extracted": extracted_dir is not None,
                "scope": "integrity_not_authenticity"}
    except (tarfile.TarError, EOFError, UnicodeError, gzip.BadGzipFile, zlib.error) as error:
        raise PolicyError("malformed or truncated crate archive") from error


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True, type=Path)
    parser.add_argument("--source-dir", type=Path, help="explicit intended source byte comparison")
    parser.add_argument("--extracted-dir", type=Path, help="compare all archive member bytes")
    args = parser.parse_args(argv)
    try:
        root = Path(__file__).resolve().parent.parent
        expected = inventory((root / "docs/package-files.txt").read_text(encoding="utf-8"))
        receipt = verify_archive(args.archive, expected, args.source_dir, args.extracted_dir)
    except (OSError, ValueError):
        # Parser/OS exception text can contain source contents or absolute paths.
        print("Package archive integrity check failed", file=sys.stderr)
        print(json.dumps({"schema_version": "ideomancer.package-archive.v1", "status": "failed"}))
        return 1
    print(json.dumps(receipt, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
