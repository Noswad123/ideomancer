def validate_package(directory):
    """Reject checkouts and unnormalized manifests; return canonical path + TOML."""
    directory = Path(directory).resolve(strict=True)
    if not directory.is_dir() or (directory / ".git").exists():
        raise ValueError("expected extracted package directory, not checkout")
    manifests = []
    for name in ("Cargo.toml", "Cargo.toml.orig"):
        with check_package_archive.checked_file(directory, name) as stream:
            content = stream.read(check_package_archive.MAX_FILE + 1)
        if len(content) > check_package_archive.MAX_FILE:
            raise ValueError("package manifest exceeds size limit")
        try:
            text = content.decode("utf-8")
            parsed = tomllib.loads(text)
        except (UnicodeError, tomllib.TOMLDecodeError, RecursionError):
            raise ValueError("invalid package manifest") from None
        for key in ("package", "lib", "target"):
            if not isinstance(parsed.get(key, {}), dict):
                raise ValueError("invalid package manifest table")
        # Validate both original and normalized dependency/feature table shapes
        # before subsequent lookups or the archive verifier can consume them.
        try:
            check_package_archive.dependency_tables(parsed)
            check_package_archive.manifest_features(parsed)
        except ValueError:
            raise ValueError("invalid package dependency or feature table") from None
        manifests.append((text, parsed))
    (text, manifest), (_, original) = manifests
    if not text.startswith(NORMALIZED_HEADER + "\n"):
        raise ValueError("expected Cargo-normalized package manifest")
    package = manifest.get("package", {})
    if package.get("name") != "ideomancer" or not isinstance(package.get("version"), str):
        raise ValueError("expected ideomancer package")
    for field in ("name", "version"):
        if package[field] != original.get("package", {}).get(field):
            raise ValueError("original and normalized package identities differ")
    library = manifest.get("lib", {})
    if library.get("name") != "ideomancer_core" or library.get("path") != "src/lib.rs":
        raise ValueError("expected normalized ideomancer_core library")
    for name in ("Cargo.toml", "Cargo.toml.orig", "src/lib.rs"):
        path = directory / name
        if not path.is_file() or not path.resolve().is_relative_to(directory):
            raise ValueError("package files must exist inside extracted directory")
    if any(key in manifest for key in ("workspace", "patch", "replace")):
        raise ValueError("expected standalone normalized package")
    tables = [manifest, *manifest.get("target", {}).values()]
    for table in tables:
        for kind in ("dependencies", "dev-dependencies", "build-dependencies"):
            for dependency in table.get(kind, {}).values():
                if isinstance(dependency, dict) and any(
                    key in dependency for key in ("path", "workspace", "git")
                ):
                    raise ValueError("expected registry-only packaged dependencies")
    return directory, manifest


def verify_package_archive(directory, manifest, expected):
    package = manifest["package"]
    # Use only a basename derived from the manifest, never an arbitrary path.
    name = f"{package['name']}-{package['version']}.crate"
    if Path(name).name != name or "\\" in name:
        raise ValueError("invalid package archive name")
    result = verify_archive(directory.parent / name, expected, extracted_dir=directory)
    if result["status"] != "passed" or result["matched_extracted"] is not True:
        raise ValueError("archive must match extracted package")
    return result


def write_consumer(root, package_dir):
    (root / "src").mkdir()
    (root / "tests").mkdir()
    # JSON strings are valid TOML basic strings, including escaped Windows paths.
    (root / "Cargo.toml").write_text(
        '[package]\nname = "ideomancer-package-consumer"\nversion = "0.0.0"\n'
        'edition = "2021"\n\n[workspace]\n\n[dependencies]\n'
        f'ideomancer = {{ path = {json.dumps(str(package_dir), ensure_ascii=False)} }}\n',
        encoding="utf-8",
    )
    (root / "src/lib.rs").write_text("// Independent downstream consumer.\n", encoding="utf-8")
    (root / "tests/public_api.rs").write_text(CONSUMER_TEST, encoding="utf-8")


def tool_command(tool, toolchain):
    if toolchain is not None and (
        not toolchain or toolchain.startswith(("-", "+"))
        or any(char.isspace() or ord(char) < 32 for char in toolchain)
    ):
        raise ValueError("invalid explicit Rust toolchain")
    return [tool, *([f"+{toolchain}"] if toolchain else [])]


def check_resolution(root):
    locked = tomllib.loads((root / "Cargo.lock").read_text(encoding="utf-8"))
    versions = [p["version"] for p in locked["package"] if p["name"] == "tree-sitter-language"]
    if versions != [ABI_VERSION]:
        raise ValueError("downstream tree-sitter-language ABI pin mismatch")
    return ABI_VERSION


def parser():
    result = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    result.add_argument("--package-dir", type=Path, required=True, help="already verified extracted Cargo package")
    result.add_argument("--toolchain", help="installed Rust toolchain, e.g. 1.89.0 (cargo +1.89.0)")
    result.add_argument("--offline", action=argparse.BooleanOptionalAction, default=True,
                        help="cached registry resolution only (default); --no-offline permits registry access")
    result.add_argument("--target-dir", type=Path, help="explicit reusable Cargo target; default: temporary target")
    return result


def main(argv=None):
    args = parser().parse_args(argv)
    receipt = {"schema_version": "ideomancer.package-consumer.v1", "status": "failed",
               "python": platform.python_version(), "offline": args.offline,
               "toolchain": args.toolchain or "default", "tool_versions": {},
               "archive_checksum": {"status": "not_verified", "sha256": None},
               "archive_integrity": {"status": "not_verified", "matched_extracted": None},
               "target": {"mode": "explicit" if args.target_dir else "temporary"},
               "resolution": "fresh_consumer_lockfile"}
    stage = "package_validation"
    try:
        package_dir, manifest = validate_package(args.package_dir)
        receipt["package"] = {key: manifest["package"].get(key) for key in ("name", "version", "rust-version")}
        stage = "archive_integrity"
        trusted_root = Path(__file__).resolve().parent.parent
        if trusted_root.is_relative_to(package_dir):
            raise ValueError("reviewer inventory must be outside candidate package")
        expected = inventory((trusted_root / "docs/package-files.txt").read_text(encoding="utf-8"))
        before = verify_package_archive(package_dir, manifest, expected)
        receipt["archive_checksum"] = {"status": "verified", "sha256": before["archive_sha256"]}
        receipt["archive_integrity"] = {"status": "verified", "matched_extracted": True}
        stage = "consumer_setup"
        cargo = tool_command("cargo", args.toolchain)
        rustc = tool_command("rustc", args.toolchain)
        target = args.target_dir.resolve() if args.target_dir else None
        if target is not None and target.is_relative_to(package_dir):
            raise ValueError("target directory must be outside extracted package")
        with tempfile.TemporaryDirectory(prefix="ideomancer-consumer-") as temporary:
            root = Path(temporary).resolve()
            if root.is_relative_to(Path(__file__).resolve().parent.parent):
                raise ValueError("consumer temporary directory must be outside engine repository")
            write_consumer(root, package_dir)
            env = os.environ.copy()
            env["RUSTUP_AUTO_INSTALL"] = "0"
            # Runtime capabilities are selected by the typed API, not inherited settings.
            for key in list(env):
                if key.startswith("IDEOMANCER_") or key in ("NODE_OPTIONS", "NODE_PATH"):
                    env.pop(key)
            stage = "tool_versions"
            for tool, command in (("cargo", cargo), ("rustc", rustc)):
                version = subprocess.run(command + ["--version"], cwd=root, env=env,
                                         text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
                receipt["tool_versions"][tool] = version.stdout.strip()
            stage = "cargo_test"
            command = cargo + ["test", "--manifest-path", str(root / "Cargo.toml"),
                               "--target-dir", str(target or root / "target"), "--test", "public_api"]
            if args.offline:
                command.append("--offline")
            # Keep stdout exclusively for the receipt, including compiler/test output.
            completed = subprocess.run(command, cwd=root, env=env, stdout=sys.stderr, stderr=sys.stderr)
            receipt["cargo_test_exit_code"] = completed.returncode
            if completed.returncode:
                raise ValueError("downstream cargo test failed")
            stage = "archive_integrity_after"
            after = verify_package_archive(package_dir, manifest, expected)
            if after["archive_sha256"] != before["archive_sha256"]:
                raise ValueError("archive changed during consumer validation")
            stage = "resolution_validation"
            receipt["tree_sitter_language"] = check_resolution(root)
        receipt["status"] = "passed"
    except (OSError, ValueError, UnicodeError, subprocess.SubprocessError):
        # Deliberately do not serialize exception text, paths, logs, or fixture data.
        receipt["failed_stage"] = stage
        if stage in ("archive_integrity", "archive_integrity_after"):
            receipt["archive_integrity"] = {"status": "failed", "matched_extracted": None}
    print(json.dumps(receipt, sort_keys=True))
    return 0 if receipt["status"] == "passed" else 1


if __name__ == "__main__":
    sys.exit(main())
